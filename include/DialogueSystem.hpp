// Вариант ответа игрока
struct DialogueOption {
    std::string text;      // Текст на кнопке выбора
    int targetNodeIndex;   // Индекс узла в векторе, куда перейдет диалог
};

// Одна фраза (узел) диалога
struct DialogueNode {
    std::string speaker;                   // Имя говорящего в верхней части окна
    std::string text;                      // Текст реплики
    std::vector<DialogueOption> options;   // Если пусто — обычный переход по любой клавише
    int nextNodeIndex = NEXT_SEQUENTIAL;   // Куда идти после фразы (по умолчанию +1)
};