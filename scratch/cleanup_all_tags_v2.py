count = 0
for old_s, new_s in replacements:
    if old_s in text:
        text = text.replace(old_s, new_s)
        count += 1
    else:
        old_norm = old_s.replace("\n", "\r\n")
        new_norm = new_s.replace("\n", "\r\n")
        if old_norm in text:
            text = text.replace(old_norm, new_norm)
            count += 1

print(f"Replaced {count} tag patterns.")

with open(cpp_path, "w", encoding="utf-8") as f:
    f.write(text)

print("Tag cleanup v2 completed.")
